# функция для высчитывания площади прямоугольника
def area(a, b): 
    # принимает a(первая сторона прямоугольника)
    # принимает b(вторая сторона прямоугольника)
    # умножает их друг на друга
    return a * b 

# функция для высчитывания периметра прямоугольника
def perimeter(a, b): 
    # принимает a(первая сторона прямоугольника)
    # принимает b(вторая сторона прямоугольника)
    # умножает их сумму на 2
    return (a + b)*2