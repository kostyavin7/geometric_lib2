import math
# библиотека для использования числа пи
def area(r):
    # принимает r - радиус круга  и возводит в кварат, после умножает на число пи
    #math.pi - вызов числа пи из библиотеки math
    return math.pi * r * r

# функция для высчитывания периметра круга
def perimeter(r):
    # принимает r - радиус круга, умножает его на число пи, после на 2
    #math.pi - вызов числа пи из библиотеки math
    return 2 * math.pi * r