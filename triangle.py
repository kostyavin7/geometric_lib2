# функция для высчитывания площади треугольника
def area(a, h):
    # принимает a(сторону треугольника)
    # принимает h(высота опущенная на эту сторону a)
    # произведение высоты и стороны делит на 2
    return a * h / 2 

# функция для вычисления периметра труегольника
def perimeter(a, b, c): 
    # принимает a(первая сторона треугольника)
    # принимает b(вторая сторона треугольника)
    # принимает c(третья сторона треугольника)
    # складывает их
    return a + b + c